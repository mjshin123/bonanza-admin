-- =========================================================
-- 14. posts RLS
-- =========================================================

create policy "public can read published posts"
on public.posts
for select
to anon
using (
  is_published = true

  and exists (
    select 1
    from public.boards
    where boards.id = posts.board_id
      and boards.is_active = true
  )
);


create policy "authenticated can manage posts"
on public.posts
for all
to authenticated
using (true)
with check (true);


-- =========================================================
-- 15. post_files RLS
-- =========================================================

create policy "public can read published post files"
on public.post_files
for select
to anon
using (
  exists (
    select 1
    from public.posts
    join public.boards
      on boards.id = posts.board_id

    where posts.id = post_files.post_id
      and posts.is_published = true
      and boards.is_active = true
  )
);


create policy "authenticated can manage post files"
on public.post_files
for all
to authenticated
using (true)
with check (true);