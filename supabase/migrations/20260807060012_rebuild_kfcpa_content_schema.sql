create index posts_organization_id_idx
on public.posts (organization_id);


create index posts_public_list_idx
on public.posts (
  board_id,
  is_pinned desc,
  published_at desc,
  created_at desc
)
where is_published = true;


create index post_files_post_id_idx
on public.post_files (
  post_id,
  sort_order
);


create index organizations_type_sort_idx
on public.organizations (
  organization_type,
  sort_order,
  name
);


